-- Metadata snapshot of works, one row per canonical key (BR-04, ADR 0005 and 0006).
-- Shared by all users; deleting a profile never deletes these rows.
CREATE TABLE media_items (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category           VARCHAR(16)  NOT NULL,
    canonical_provider VARCHAR(32)  NOT NULL,
    external_id        VARCHAR(64)  NOT NULL,
    title              VARCHAR(500) NOT NULL,
    year               INTEGER,
    image_url          VARCHAR(500),
    adult              BOOLEAN      NOT NULL DEFAULT false,
    fetched_at         TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT media_items_canonical_key UNIQUE (category, canonical_provider, external_id),
    CONSTRAINT media_items_category CHECK (category IN ('MOVIE', 'SERIES', 'ANIME', 'MANGA', 'BOOK', 'GAME', 'MUSIC'))
);

-- Ids of the same work in other sources (Letterboxd carries the TMDB id, Steam app ids map through IGDB).
CREATE TABLE media_external_ids (
    media_item_id BIGINT      NOT NULL REFERENCES media_items (id) ON DELETE CASCADE,
    provider      VARCHAR(32) NOT NULL,
    external_id   VARCHAR(64) NOT NULL,
    CONSTRAINT media_external_ids_pkey PRIMARY KEY (provider, external_id)
);
CREATE INDEX media_external_ids_media_item_idx ON media_external_ids (media_item_id);
