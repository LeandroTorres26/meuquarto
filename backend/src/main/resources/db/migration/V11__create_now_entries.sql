-- "Agora" overrides (FR-15, BR-06): one row per (profile, category) only when the owner changed something.
-- No row, or source AUTO with hidden false, means "automatic": the profile shows the latest synced item of the
-- category, computed on read from collection_items, so it never goes stale.
--   MANUAL: the owner pinned collection_item_id (then hidden is false).
--   AUTO + hidden: the owner hid the category on the profile.
-- Deleting the pinned collection item deletes the row, which puts the category back on automatic.
CREATE TABLE now_entries (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    profile_id         BIGINT      NOT NULL REFERENCES profiles (id) ON DELETE CASCADE,
    category           VARCHAR(16) NOT NULL,
    collection_item_id BIGINT      REFERENCES collection_items (id) ON DELETE CASCADE,
    source             VARCHAR(8)  NOT NULL DEFAULT 'AUTO',
    hidden             BOOLEAN     NOT NULL DEFAULT false,
    CONSTRAINT now_entries_profile_category_key UNIQUE (profile_id, category),
    CONSTRAINT now_entries_category CHECK (category IN ('MOVIE', 'SERIES', 'ANIME', 'MANGA', 'BOOK', 'GAME', 'MUSIC')),
    CONSTRAINT now_entries_source CHECK (source IN ('AUTO', 'MANUAL')),
    CONSTRAINT now_entries_shape CHECK (
        (source = 'MANUAL' AND collection_item_id IS NOT NULL AND NOT hidden)
        OR (source = 'AUTO' AND collection_item_id IS NULL))
);
CREATE INDEX now_entries_item_idx ON now_entries (collection_item_id);
