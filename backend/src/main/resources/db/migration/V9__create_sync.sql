-- Sync engine (#29, ADR 0007).

-- Scheduling state of an account. last_sync_started_at is what the manual cooldown counts from (BR-03);
-- consecutive_failures and next_attempt_at are the exponential backoff after failed runs.
ALTER TABLE linked_accounts
    ADD COLUMN last_sync_started_at TIMESTAMPTZ,
    ADD COLUMN consecutive_failures INTEGER NOT NULL DEFAULT 0,
    ADD COLUMN next_attempt_at      TIMESTAMPTZ,
    ADD CONSTRAINT linked_accounts_failures_not_negative CHECK (consecutive_failures >= 0);

-- The scheduler picks the accounts with the oldest successful sync first (NULL = never synced).
CREATE INDEX linked_accounts_due_idx ON linked_accounts (last_synced_at NULLS FIRST, id);

-- Raw activity read from the platforms (dates, watched-on). One row per (account, work, kind, time),
-- so a second run over the same feed inserts nothing. Deleted with the account (FR-16).
CREATE TABLE synced_entries (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    linked_account_id BIGINT      NOT NULL REFERENCES linked_accounts (id) ON DELETE CASCADE,
    media_item_id     BIGINT      NOT NULL REFERENCES media_items (id),
    activity_type     VARCHAR(16) NOT NULL,
    occurred_at       TIMESTAMPTZ NOT NULL,
    created_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT synced_entries_dedup_key UNIQUE (linked_account_id, media_item_id, activity_type, occurred_at),
    CONSTRAINT synced_entries_activity_type CHECK (activity_type IN ('FINISHED', 'IN_PROGRESS', 'OWNED', 'LOVED'))
);
CREATE INDEX synced_entries_media_item_idx ON synced_entries (media_item_id);

-- One row per sync attempt, for observability. `error` holds a code from our own list, never text from
-- a provider. Deleted with the account.
CREATE TABLE sync_runs (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    linked_account_id BIGINT      NOT NULL REFERENCES linked_accounts (id) ON DELETE CASCADE,
    started_at        TIMESTAMPTZ NOT NULL,
    finished_at       TIMESTAMPTZ NOT NULL,
    status            VARCHAR(16) NOT NULL,
    items_count       INTEGER     NOT NULL DEFAULT 0,
    error             VARCHAR(64),
    CONSTRAINT sync_runs_status CHECK (status IN ('SUCCESS', 'FAILED', 'SKIPPED')),
    CONSTRAINT sync_runs_items_count CHECK (items_count >= 0)
);
CREATE INDEX sync_runs_account_idx ON sync_runs (linked_account_id, started_at DESC);
