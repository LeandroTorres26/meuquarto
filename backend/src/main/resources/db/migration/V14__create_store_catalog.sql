-- The store catalog and what users own (FR-17, BR-05, data-model). The catalog is seeded here, there is
-- no admin panel. Prices are in cents (BRL). stripe_price_ref stays null until the Stripe checkout (#38)
-- fills it. entitlements has no rows until a verified webhook grants one (BR-09, #38); order_id gets its
-- foreign key when the orders table arrives.
CREATE TABLE products (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku              VARCHAR(40)  NOT NULL,
    name             VARCHAR(80)  NOT NULL,
    type             VARCHAR(10)  NOT NULL,
    price_cents      INTEGER      NOT NULL,
    active           BOOLEAN      NOT NULL DEFAULT TRUE,
    stripe_price_ref VARCHAR(100),
    CONSTRAINT products_sku_key UNIQUE (sku),
    CONSTRAINT products_type_valid CHECK (type IN ('THEME', 'PACK')),
    CONSTRAINT products_price_positive CHECK (price_cents > 0)
);

-- A theme is free when product_id is null. Its colors are not stored: they live in the design system
-- CSS, selected by data-theme="<id>", so the id is the only link between this row and the front end.
CREATE TABLE themes (
    id         VARCHAR(30) PRIMARY KEY,
    product_id BIGINT      REFERENCES products (id),
    name       VARCHAR(40) NOT NULL,
    CONSTRAINT themes_id_format CHECK (id ~ '^[a-z]+$'),
    CONSTRAINT themes_product_key UNIQUE (product_id)
);

CREATE TABLE entitlements (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    product_id BIGINT      NOT NULL REFERENCES products (id),
    granted_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    order_id   BIGINT,
    -- Purchases are permanent and bought once (BR-05).
    CONSTRAINT entitlements_user_product_key UNIQUE (user_id, product_id)
);

