-- Highlights (FR-09a, FR-11, ADR 0011): the ordered subset of the collection shown on the profile home.
-- category NULL is the "Favoritos de tudo" list. NULLS NOT DISTINCT (PostgreSQL 15+) makes the unique
-- constraint treat two NULLs as equal, so a profile cannot get two favorites lists.
CREATE TABLE highlight_lists (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    profile_id BIGINT      NOT NULL REFERENCES profiles (id) ON DELETE CASCADE,
    category   VARCHAR(16),
    CONSTRAINT highlight_lists_profile_category_key UNIQUE NULLS NOT DISTINCT (profile_id, category),
    CONSTRAINT highlight_lists_category CHECK (category IS NULL OR category IN ('MOVIE', 'SERIES', 'ANIME', 'MANGA', 'BOOK', 'GAME', 'MUSIC'))
);

-- The size limit (BR-02) depends on the plan, so it is a domain rule, not a constraint.
-- Deleting the collection item removes its highlights (hiding does it in the domain).
CREATE TABLE highlights (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    list_id            BIGINT NOT NULL REFERENCES highlight_lists (id) ON DELETE CASCADE,
    collection_item_id BIGINT NOT NULL REFERENCES collection_items (id) ON DELETE CASCADE,
    position           INT    NOT NULL,
    CONSTRAINT highlights_list_item_key UNIQUE (list_id, collection_item_id),
    CONSTRAINT highlights_position CHECK (position >= 0)
);
CREATE INDEX highlights_item_idx ON highlights (collection_item_id);
