-- The owner's collection per profile (FR-08, ADR 0011): no size limit, one row per work (BR-07).
-- `hidden` keeps a synced item out of the visible collection and stops sync from bringing it back.
CREATE TABLE collection_items (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    profile_id       BIGINT       NOT NULL REFERENCES profiles (id) ON DELETE CASCADE,
    media_item_id    BIGINT       NOT NULL REFERENCES media_items (id),
    category         VARCHAR(16)  NOT NULL,
    note             VARCHAR(140),
    hidden           BOOLEAN      NOT NULL DEFAULT false,
    added_at         TIMESTAMPTZ  NOT NULL DEFAULT now(),
    last_activity_at TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT collection_items_profile_media_key UNIQUE (profile_id, media_item_id),
    CONSTRAINT collection_items_category CHECK (category IN ('MOVIE', 'SERIES', 'ANIME', 'MANGA', 'BOOK', 'GAME', 'MUSIC')),
    -- A note is either absent or has visible text; the domain trims, this keeps bad data out anyway.
    CONSTRAINT collection_items_note_not_blank CHECK (note IS NULL OR char_length(btrim(note)) > 0)
);
-- Listing per category, most recent first (ADR 0011).
CREATE INDEX collection_items_listing_idx ON collection_items (profile_id, category, last_activity_at DESC);
CREATE INDEX collection_items_media_item_idx ON collection_items (media_item_id);

-- Why an item is in the collection: MANUAL, or the name of the provider that synced it.
-- linked_account_id gets its foreign key with the linked_accounts table (sync epic).
CREATE TABLE collection_item_sources (
    collection_item_id BIGINT      NOT NULL REFERENCES collection_items (id) ON DELETE CASCADE,
    source             VARCHAR(32) NOT NULL,
    linked_account_id  BIGINT,
    first_seen_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT collection_item_sources_pkey PRIMARY KEY (collection_item_id, source),
    CONSTRAINT collection_item_sources_source CHECK (source ~ '^[A-Z][A-Z_]*$')
);
