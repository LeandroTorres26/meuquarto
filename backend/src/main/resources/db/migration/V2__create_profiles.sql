-- Profiles and their public slug (BR-01). The foreign key to users is added with the users table (#10).
CREATE TABLE profiles (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT      NOT NULL,
    slug       VARCHAR(30) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT profiles_user_id_key UNIQUE (user_id),
    CONSTRAINT profiles_slug_key UNIQUE (slug),
    -- Same format as the domain rule, so bad data cannot get in even outside the API.
    CONSTRAINT profiles_slug_format CHECK (
        char_length(slug) BETWEEN 3 AND 30 AND slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$'
    )
);
