-- External accounts linked by public username (FR-12, ADR 0004): no token is ever stored.
CREATE TABLE linked_accounts (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    profile_id     BIGINT       NOT NULL REFERENCES profiles (id) ON DELETE CASCADE,
    provider       VARCHAR(16)  NOT NULL,
    username       VARCHAR(64)  NOT NULL,
    status         VARCHAR(16)  NOT NULL DEFAULT 'ACTIVE',
    last_synced_at TIMESTAMPTZ,
    last_error     VARCHAR(200),
    created_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT linked_accounts_profile_provider_key UNIQUE (profile_id, provider),
    CONSTRAINT linked_accounts_provider CHECK (provider IN ('LETTERBOXD', 'ANILIST', 'STEAM', 'LASTFM', 'GOODREADS')),
    CONSTRAINT linked_accounts_status CHECK (status IN ('ACTIVE', 'ERROR')),
    CONSTRAINT linked_accounts_username_not_blank CHECK (char_length(btrim(username)) > 0)
);

-- The foreign key V6 left out. SET NULL is only a safety net: unlinking releases the items first (FR-16).
-- Rows that point to an account that does not exist (there could be none, no sync existed yet) are cleared.
UPDATE collection_item_sources SET linked_account_id = NULL WHERE linked_account_id IS NOT NULL;
ALTER TABLE collection_item_sources
    ADD CONSTRAINT collection_item_sources_linked_account_fkey
    FOREIGN KEY (linked_account_id) REFERENCES linked_accounts (id) ON DELETE SET NULL;
CREATE INDEX collection_item_sources_account_idx ON collection_item_sources (linked_account_id)
    WHERE linked_account_id IS NOT NULL;
